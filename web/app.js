  function readStore(key, fallback) {
    try { const v = localStorage.getItem(key); return v ? JSON.parse(v) : fallback; } catch (e) { return fallback; }
  }
  function writeStore(key, value) {
    try { localStorage.setItem(key, JSON.stringify(value)); } catch (e) { /* private mode: fine */ }
  }

  // ---------------------------------------------------------------- data access
  async function getJSON(url, opts) {
    const res = await fetch(url, Object.assign({ headers: { "Accept": "application/json" } }, opts || {}));
    let body = null;
    try { body = await res.json(); } catch (e) { throw new Error("not-json"); }
    if (!res.ok) {
      const err = new Error((body && body.error) || ("HTTP " + res.status));
      err.apiError = true;
      throw err;
    }
    return body;
  }

