  function drawCharts(root) {
    (root || document).querySelectorAll("[data-chart]").forEach((h) => {
      const fn = chartFns.get(h.dataset.chart);
      if (!fn) return;
      const w = Math.max(240, Math.round(h.clientWidth));
      if (h._w === w) return;
      const first = h._w == null;
      h._w = w;
      h.innerHTML = fn(w, first);
    });
  }
