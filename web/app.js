  function usualRows(b) {
    const rows = [];
    if (isNum(b.readiness)) {
      const base = isNum(b.readiness_baseline) ? b.readiness_baseline : null;
      const dl = base != null ? b.readiness - base : null;
      rows.push({
        name: "Readiness", sub: "Oura score",
        value: String(b.readiness),
        delta: dl == null ? "out of 100" : Math.abs(dl) <= 2 ? "about usual" : Math.abs(dl) + (dl < 0 ? " below usual" : " above usual"),
        scale: dl == null ? (b.readiness - 75) : dl, range: 20,
      });
    }
    if (isNum(b.total_sleep_min)) {
      const base = isNum(b.total_sleep_baseline_min) ? b.total_sleep_baseline_min : null;
      const dl = base != null ? b.total_sleep_min - base : null;
      rows.push({
        name: "Sleep", sub: isNum(b.sleep_score) ? "score " + b.sleep_score : "last night",
        value: fmtDur(b.total_sleep_min),
        delta: dl == null ? "last night" : Math.abs(dl) < 15 ? "about usual" : fmtDur(Math.abs(dl)) + (dl < 0 ? " less" : " more"),
        scale: dl == null ? 0 : dl, range: 120,
      });
    }
    if (isNum(b.hrv)) {
      const dl = isNum(b.hrv_delta_pct) ? b.hrv_delta_pct : (isNum(b.hrv_baseline) ? (b.hrv - b.hrv_baseline) / b.hrv_baseline * 100 : null);
      rows.push({
        name: "HRV", sub: isNum(b.hrv_baseline) ? "usual " + b.hrv_baseline + " ms" : "overnight",
        value: b.hrv + " ms",
        delta: dl == null ? "overnight" : Math.abs(dl) < 5 ? "about usual" : Math.round(Math.abs(dl)) + "% " + (dl < 0 ? "lower" : "higher"),
        scale: dl || 0, range: 30,
      });
    }
    if (isNum(b.rhr)) {
      const dl = isNum(b.rhr_delta) ? b.rhr_delta : (isNum(b.rhr_baseline) ? b.rhr - b.rhr_baseline : null);
      rows.push({
        name: "Resting HR", sub: isNum(b.rhr_baseline) ? "usual " + b.rhr_baseline + " bpm" : "overnight low",
        value: b.rhr + " bpm",
        delta: dl == null ? "overnight low" : Math.abs(dl) <= 1 ? "about usual" : Math.abs(dl) + " bpm " + (dl > 0 ? "higher" : "lower"),
        scale: dl || 0, range: 10,
      });
    }
    return rows;
  }

