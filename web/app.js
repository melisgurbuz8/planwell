  function slugify(label, taken) {
    let base = String(label || "activity").toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "") || "activity";
    let k = base, n = 2;
    while (taken.has(k)) k = base + "_" + n++;
    return k;
  }

