  // Calendar titles can be raw ("[solidcore] Arms + Abs", "Solidcore — Full Body", "Padel w/ Ana").
  // When a title starts with the label (or a [tag]), lead with the label and keep the rest as a subtitle.
  function titleParts(c) {
    const label = actName(c.activity, c);
    let raw = String(c.title || "").trim();
    if (!raw) return { title: label, cls: "" };
    const lead = new RegExp("^\\[?\\s*" + label.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "\\b\\s*\\]?\\s*[—–:\\-|]*\\s*", "i");
    if (!lead.test(raw) && !/^\[[^\]]*\]/.test(raw)) return { title: raw, cls: "" };
    raw = raw.replace(lead, "").replace(/^\[[^\]]*\]\s*/, "").trim();
    return { title: label, cls: raw && raw.toLowerCase() !== label.toLowerCase() ? raw : "" };
  }
  const titleHTML = (c) => { const t = titleParts(c); return esc(t.title) + (t.cls ? ' <span class="act-cls">' + esc(t.cls) + "</span>" : ""); };
