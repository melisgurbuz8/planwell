  function hrChartSVG(session, hr, width) {
    const { zones, thr } = zonesCfg();
    const pts = (hr || []).map((p) => ({ t: new Date(p.t).getTime(), bpm: p.bpm })).filter((p) => isNum(p.bpm) && isFinite(p.t));
    if (pts.length < 2) return '<p class="sub">No heart-rate samples were recorded for this session.</p>';
    const t0 = new Date(session.start).getTime() || pts[0].t;
    const W = width || 720, H = W < 520 ? 240 : 300, L = 38, R = 12, T = 16, B = 30;
    const minutes = pts.map((p) => (p.t - t0) / 60000);
    const maxM = Math.max.apply(null, minutes);
    const bpms = pts.map((p) => p.bpm);
    const yMin = Math.min(70, Math.floor((Math.min.apply(null, bpms) - 5) / 10) * 10);
    const yMax = Math.max(thr + 20, Math.ceil((Math.max.apply(null, bpms) + 8) / 10) * 10);
    const x = (m) => L + (m / maxM) * (W - L - R);
    const y = (b) => T + (1 - (b - yMin) / (yMax - yMin)) * (H - T - B);
    let s = "";
    // zone bands
    const bounds = [yMin].concat(zones).concat([yMax]);
    for (let i = 0; i < 5; i++) {
      const lo = Math.max(yMin, bounds[i]), hi = Math.min(yMax, bounds[i + 1]);
      if (hi > lo) s += '<rect class="zone-band" x="' + L + '" width="' + (W - L - R) + '" y="' + y(hi) + '" height="' + (y(lo) - y(hi)) + '" fill="var(--z' + (i + 1) + ')"/>';
    }
    // y grid
    for (let b = Math.ceil(yMin / 20) * 20; b <= yMax; b += 20) {
      s += '<line class="gridline" x1="' + L + '" x2="' + (W - R) + '" y1="' + y(b) + '" y2="' + y(b) + '"/><text x="' + (L - 8) + '" y="' + (y(b) + 4) + '" text-anchor="end">' + b + "</text>";
    }
    // x ticks
    const step = maxM > 70 || W < 420 ? 20 : 10;
    for (let m = 0; m <= maxM; m += step) {
      s += '<text x="' + x(m) + '" y="' + (H - 10) + '" text-anchor="middle">' + m + "</text>";
    }
    s += '<text x="' + (W - R) + '" y="' + (H - 10) + '" text-anchor="end" dx="0" style="display:none">min</text>';
    // session end
    if (isNum(session.duration_min) && session.duration_min < maxM) {
      const ex = x(session.duration_min);
      s += '<line class="end-mark" x1="' + ex + '" x2="' + ex + '" y1="' + T + '" y2="' + (H - B) + '"/>';
      s += '<text x="' + (ex + 6) + '" y="' + (T + 12) + '">' + (W - ex > 150 ? "Session ends, cool-down after" : "Ends") + "</text>";
    }
    // threshold
    s += '<line class="thr-line" x1="' + L + '" x2="' + (W - R) + '" y1="' + y(thr) + '" y2="' + y(thr) + '"/>';
    s += '<text class="thr-text" x="' + (L + 8) + '" y="' + (y(thr) - 7) + '">Your threshold, ' + thr + " bpm</text>";
    // line, with above-threshold portion re-drawn through a clip
    const d = pts.map((p, i) => (i ? "L" : "M") + x(minutes[i]).toFixed(1) + " " + y(p.bpm).toFixed(1)).join(" ");
    const cid = "clip-above-" + Math.random().toString(36).slice(2, 8);
    s += '<clipPath id="' + cid + '"><rect x="0" y="0" width="' + W + '" height="' + y(thr) + '"/></clipPath>';
    s += '<path class="hr-line" d="' + d + '"/>';
    s += '<path class="hr-above" d="' + d + '" clip-path="url(#' + cid + ')"/>';
    const peak = Math.max.apply(null, bpms);
    const desc = "Heart rate over " + Math.round(maxM) + " minutes, from " + Math.min.apply(null, bpms) + " to " + peak + " bpm. " +
      (session.minutes_above_threshold || 0) + " minutes were above your threshold of " + thr + " bpm.";
    return '<svg class="hr-chart" width="' + W + '" height="' + H + '" viewBox="0 0 ' + W + " " + H + '" role="img" aria-label="' + esc(desc) + '">' + s + "</svg>" +
      "";
  }

